GRANT SELECT ON ALL TABLES IN SCHEMA chatbot TO chatbot_app;
GRANT INSERT,UPDATE ON chatbot.settings,chatbot.versions,chatbot.jobs,chatbot.whatsapp_inbox,chatbot.whatsapp_receipts TO chatbot_app;
GRANT INSERT,DELETE ON chatbot.sessions TO chatbot_app;
GRANT INSERT ON chatbot.conversations TO chatbot_app;
GRANT INSERT,DELETE ON chatbot.login_attempts TO chatbot_app;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA chatbot TO chatbot_app;
GRANT UPDATE(first_live_write_at) ON chatbot.runtime_control TO chatbot_app;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['settings','users','sessions','versions','jobs','conversations',
      'whatsapp_inbox','whatsapp_receipts','login_attempts','schema_migrations','state_imports','runtime_control'] LOOP
    EXECUTE format('ALTER TABLE chatbot.%I ENABLE ROW LEVEL SECURITY',t);
    EXECUTE format('REVOKE ALL ON chatbot.%I FROM PUBLIC,anon,authenticated',t);
    EXECUTE format('CREATE POLICY backend_read ON chatbot.%I FOR SELECT TO chatbot_app USING(true)',t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY['settings','versions','jobs','whatsapp_inbox','whatsapp_receipts'] LOOP
    EXECUTE format('CREATE POLICY backend_insert ON chatbot.%I FOR INSERT TO chatbot_app WITH CHECK(true)',t);
    EXECUTE format('CREATE POLICY backend_update ON chatbot.%I FOR UPDATE TO chatbot_app USING(true) WITH CHECK(true)',t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY['sessions','conversations','login_attempts'] LOOP
    EXECUTE format('CREATE POLICY backend_insert ON chatbot.%I FOR INSERT TO chatbot_app WITH CHECK(true)',t);
  END LOOP;
  FOREACH t IN ARRAY ARRAY['sessions','login_attempts'] LOOP
    EXECUTE format('CREATE POLICY backend_delete ON chatbot.%I FOR DELETE TO chatbot_app USING(true)',t);
  END LOOP;
END $$;
