DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='chatbot_app') THEN
    CREATE ROLE chatbot_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
  ELSIF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='chatbot_app'
               AND (rolsuper OR rolcreatedb OR rolcreaterole OR rolreplication OR rolbypassrls))
     OR EXISTS (SELECT 1 FROM pg_auth_members WHERE member=(SELECT oid FROM pg_roles WHERE rolname='chatbot_app')) THEN
    RAISE EXCEPTION 'Existing chatbot_app role has unexpected privileges';
  END IF;
END $$;

CREATE SCHEMA chatbot;
REVOKE ALL ON SCHEMA chatbot FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA chatbot TO chatbot_app;

CREATE TABLE chatbot.settings (key text PRIMARY KEY,value text NOT NULL);
CREATE TABLE chatbot.users (name text PRIMARY KEY,salt text,password_hash text);
CREATE TABLE chatbot.sessions (token_hash text PRIMARY KEY,expires double precision,csrf text);
CREATE TABLE chatbot.versions (
 id text PRIMARY KEY,namespace text UNIQUE,status text,created_at text,manifest text,records text,error text
);
CREATE UNIQUE INDEX one_published ON chatbot.versions(status) WHERE status='published';
CREATE TABLE chatbot.jobs (
 id text PRIMARY KEY,kind text,status text,payload text,result text,error text,
 created_at text,updated_at text,progress text NOT NULL DEFAULT '{}'
);
CREATE TABLE chatbot.conversations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session_id text,channel text,
 question text,answer text,usage text,latency double precision,trace_id text,created_at text
);
CREATE INDEX conversation_session ON chatbot.conversations(session_id,id);
CREATE TABLE chatbot.whatsapp_inbox (
 session text,message_id text,sender text,body text,status text,answer text,media_url text,
 reply_ids text,error text,created_at text,updated_at text,PRIMARY KEY(session,message_id)
);
CREATE INDEX inbox_queue ON chatbot.whatsapp_inbox(session,status,created_at,message_id);
CREATE TABLE chatbot.whatsapp_receipts (
 message_id text PRIMARY KEY,ack integer CHECK(ack BETWEEN -1 AND 4),updated_at text
);
CREATE TABLE chatbot.login_attempts (client_hash text NOT NULL,attempted_at double precision NOT NULL);
CREATE INDEX login_attempt_identity ON chatbot.login_attempts(client_hash,attempted_at);
CREATE TABLE chatbot.schema_migrations (version integer PRIMARY KEY);
CREATE TABLE chatbot.state_imports (snapshot_sha256 text PRIMARY KEY,manifest text NOT NULL,imported_at text NOT NULL);
CREATE TABLE chatbot.runtime_control (
 id integer PRIMARY KEY CHECK(id=1),mode text NOT NULL CHECK(mode IN ('closed','intake','live')),
 cutover_started_at text,first_live_write_at text
);
INSERT INTO chatbot.schema_migrations VALUES(1);
